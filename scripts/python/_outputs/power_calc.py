"""Ex-ante power / minimum detectable effect (MDE) calculations.

Two preregistered tests:

  H1: between-subject test of two proportions (delegation rates across
      Punishment vs No-Punishment), n = 80 per cell.
      MDE reported in proportion-difference units, for three baseline rates
      (p0 in {0.3, 0.5, 0.7}).

  H2: within-subject paired-mean-difference test on Player B's punishment in
      the bad-outcome cell (delegated vs non-delegated), n = 80.
      MDE = (z_{a/2} + z_b) * sigma_d / sqrt(n) is linear in the within-subject
      SD of the punishment difference. Following Felix's instruction, sigma_d
      is hypothesised as a share of an anchor effect (e.g. delta_anchor =
      pounds 0.20, the equivalence bound used in the Result 2 TOST). We
      tabulate the implied MDE in pounds for sigma_d in {0.5, 1, 2, 3, 4} *
      delta_anchor.

Constants
---------
alpha = 0.05 (two-sided), power = 0.80.

Outputs
-------
- tables/power_mde.tex   : LaTeX fragment with one small table for each test.
- _outputs/numbers.json  : updated with the headline MDE numbers cited in
                           the appendix prose.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TABLES = ROOT / "tables"
NUMBERS = Path(__file__).with_name("numbers.json")

ALPHA = 0.05
POWER = 0.80
N_PER_CELL = 80
# Standard-normal quantiles, hard-coded (no scipy in the default env).
Z_ALPHA = 1.959963984540054   # Phi^{-1}(1 - 0.05/2)
Z_BETA = 0.8416212335729143   # Phi^{-1}(0.80)


def mde_two_proportions(p0: float, n: int = N_PER_CELL) -> float:
    """Minimum detectable difference d = p1 - p0 for a two-sample z-test of
    proportions, given baseline p0, equal n per group, two-sided alpha=0.05,
    power=0.80. Solves the standard formula by fixed-point iteration on p1."""
    p1 = p0 + 0.05
    for _ in range(200):
        p_bar = (p0 + p1) / 2
        se_null = math.sqrt(2 * p_bar * (1 - p_bar) / n)
        se_alt = math.sqrt((p0 * (1 - p0) + p1 * (1 - p1)) / n)
        d_new = (Z_ALPHA * se_null + Z_BETA * se_alt)
        p1_new = p0 + d_new
        if abs(p1_new - p1) < 1e-7:
            p1 = p1_new
            break
        p1 = p1_new
    return p1 - p0


def mde_paired_pounds(sigma_d: float, n: int = N_PER_CELL) -> float:
    """MDE for a paired-mean-difference test, in the same units as sigma_d.
    MDE = (z_{alpha/2} + z_beta) * sigma_d / sqrt(n)."""
    return (Z_ALPHA + Z_BETA) * sigma_d / math.sqrt(n)


def main() -> None:
    # H1: two-proportion MDEs for three baselines.
    h1_baselines = [0.30, 0.50, 0.70]
    h1 = [(p0, mde_two_proportions(p0)) for p0 in h1_baselines]

    # H2: paired-test MDE in pounds for sigma_d as multiples of the anchor
    # effect (delta_anchor = pounds 0.20, the equivalence bound from Result 2).
    delta_anchor = 0.20
    cs = [0.5, 1.0, 2.0, 3.0, 4.0]
    h2 = [(c, c * delta_anchor, mde_paired_pounds(c * delta_anchor)) for c in cs]

    # ---------- LaTeX fragment ----------
    lines: list[str] = []
    lines.append(
        "% Auto-generated by scripts/python/_outputs/power_calc.py. Do not edit."
    )
    lines.append("\\begin{tabular}{lll}")
    lines.append("\\hline\\hline")
    lines.append(
        "Hypothesis & Assumption & Minimum detectable effect \\\\"
    )
    lines.append("\\hline")
    for p0, d in h1:
        lines.append(
            f"H1 (delegation, two-proportion test) & Baseline $p_0={p0:.2f}$ & "
            f"$\\Delta = {d:.3f}$ ({d*100:.1f} pp) \\\\"
        )
    lines.append("\\hline")
    for c, sd, m in h2:
        share = f"{int(c)}" if c == int(c) else f"{c:.1f}"
        lines.append(
            f"H2 (paired, within-subject) & $\\sigma_d = {share}\\,\\delta_a = "
            f"\\pounds {sd:.2f}$ & $\\Delta = \\pounds {m:.3f}$ \\\\"
        )
    lines.append("\\hline\\hline")
    lines.append(
        "\\multicolumn{3}{p{0.95\\textwidth}}{\\footnotesize \\textit{Note:} "
        f"Both tests assume $n = {N_PER_CELL}$ per role per condition, "
        f"$\\alpha = {ALPHA}$ two-sided, power $= {POWER:.2f}$. For H2, "
        f"$\\sigma_d$ is the within-subject standard deviation of the "
        f"punishment difference (delegated minus non-delegated, conditional "
        f"on bad outcome) and is expressed as a multiple of the anchor effect "
        f"$\\delta_a = \\pounds 0.20$ (the equivalence bound used in Result~2 "
        f"in the body of the paper, equal to $10\\%$ of the maximum punishment "
        f"of $\\pounds 2$). $\\Delta$ is the corresponding minimum detectable "
        f"effect in pounds.}}"
    )
    lines.append("\\end{tabular}")

    out = TABLES / "power_mde.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  wrote {out}")

    # ---------- numbers manifest ----------
    headline = {
        "h1_mde_p0_50": round(mde_two_proportions(0.50), 3),
        "h1_mde_p0_30": round(mde_two_proportions(0.30), 3),
        "h2_mde_sigma_eq_anchor": round(mde_paired_pounds(0.20), 3),
        "h2_mde_sigma_2x_anchor": round(mde_paired_pounds(0.40), 3),
        "n_per_cell": N_PER_CELL,
        "alpha": ALPHA,
        "power": POWER,
    }
    if NUMBERS.exists():
        existing = json.loads(NUMBERS.read_text(encoding="utf-8"))
    else:
        existing = {}
    existing.update({f"power_{k}": v for k, v in headline.items()})
    NUMBERS.write_text(json.dumps(existing, indent=2), encoding="utf-8")
    for k, v in headline.items():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
